const rows = JSON.parse(fs.readFileSync("prompts.json", "utf8"));
if (!Array.isArray(rows) || rows.length !== 100) {
  console.error("Ожидается массив из 100 строк в prompts.json");
  process.exit(1);
}
if (CATEGORIES.length !== 100) {
  console.error("Внутренняя ошибка: CATEGORIES.length !== 100");
  process.exit(1);
}

const sorted = [...rows].sort(
  (a, b) => Number(a.ID ?? a.id) - Number(b.ID ?? b.id)
);
const out = sorted.map((row, i) => {
  const id = Number(row.ID ?? row.id);
  const category = CATEGORIES[i];
  const promt =
    PROMT_OVERRIDE[id] ?? row["promt ru"] ?? row.promt ?? "";
  return {
    id,
    category,
    promt,
    url: row.url,
  };
});

fs.writeFileSync("prompts.json", JSON.stringify(out, null, 2) + "\n");
console.log("✅ cloudinary/prompts.json → id, category, promt, url (url без изменений)");

const sheetRows = out.map((r) => ({
  ID: r.id,
  category: r.category,
  "promt en": "",
  "promt ru": r.promt,
  url: r.url,
}));
const wb = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(
  wb,
  XLSX.utils.json_to_sheet(sheetRows),
  "PROMPTS"
);
XLSX.writeFile(wb, "prompts.xlsx");
console.log("✅ prompts.xlsx синхронизирован (ID, category, promt ru, url)");
